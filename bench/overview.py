"""Combine the per-run reports into bench/results.md. Run after bench.report for each run:

python -m bench.overview
"""

import csv
import shutil
from pathlib import Path

BENCH = Path(__file__).resolve().parent

# (column title, report folder, system inside that report)
COLUMNS = [
    ("Filed, reviewer can block (dev set)", "dev_reviewer_gate", "filed"),
    ("Filed, reviewer off (dev set)", "dev_reviewer_off", "filed"),
    ("Single prompt (dev set)", "dev_reviewer_off", "baseline"),
    ("Filed, reviewer off (held-out)", "heldout", "filed"),
    ("Single prompt (held-out)", "heldout", "baseline"),
]
ROWS = [
    ("Exact return (form, regime and tax within Rs 10)", "exact_return_rate", "pct"),
    ("Hands-off rate (finished correctly, no person)", "hands_off_rate", "pct"),
    (
        "False-automation rate (marked ready but wrong; lower is better)",
        "false_automation_rate",
        "pct",
    ),
    ("Escalation recall (cases needing a person that were escalated)", "escalation_recall", "pct"),
    ("Escalation precision (escalations that were needed)", "escalation_precision", "pct"),
    ("Regime choice correct", "regime_accuracy", "pct"),
    ("Mean absolute tax error, Rs", "mean_abs_error_rupees", "num"),
    ("Tokens per case", "tokens_per_case", "num"),
]


def load(folder):
    with open(BENCH / folder / "summary.csv", newline="", encoding="utf-8") as f:
        return {(r["system"], r["metric"]): r["mean"] for r in csv.DictReader(f)}


def cell(value, kind):
    if value in ("", "None", None):
        return "n/a"
    number = float(value)
    return f"{number * 100:.1f}%" if kind == "pct" else f"{number:,.0f}"


def case_count(folder):
    text = (BENCH / folder / "results.md").read_text(encoding="utf-8")
    return text.split("Cases: ")[1].split(" ")[0]


def main():
    data = {folder: load(folder) for _, folder, _ in COLUMNS}
    head = "| Metric | " + " | ".join(title for title, _, _ in COLUMNS) + " |"
    lines = [head, "|---|" + "---|" * len(COLUMNS)]
    for label, key, kind in ROWS:
        cells = [cell(data[folder].get((system, key)), kind) for _, folder, system in COLUMNS]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    text = f"""# Benchmark results

Model for every run: `gemini-3.5-flash-lite` (free tier), temperature 0. One repeat each, so there is no spread to report.
Dev set: {case_count("dev_reviewer_gate")} synthetic taxpayers (seed 7), used while building the system.
Held-out set: {case_count("heldout")} synthetic taxpayers (seed 99), never looked at before the final configuration was fixed. The run was stopped early, so only the first {case_count("heldout")} of its 50 cases were scored.
Every number comes from the saved runs in `runs/`; this file is generated by `python -m bench.overview`.

{chr(10).join(lines)}

![chart](chart.png)

## What the numbers say

- **The agents beat a single prompt by a wide margin.** On both sets Filed gets every return exactly right and never marks a wrong return as ready; the single prompt gets about one in six exactly right and marks most wrong returns as ready. The main reason is not reading ability but that the tax arithmetic, the regime comparison and the reconciliation rules are code, not model output.
- **Our first configuration over-escalated, and we changed it.** In the first run (column 1) a model reviewer could send a case to the expert. It sent 32 of the 40 cases that needed no person to the expert. Every objection we read was wrong, for example objecting to 80C claims "under the new regime" although the engine already ignores them there (we read a handful, not all 32). Hands-off rate was 16% and escalation precision 24%. The reviewer is now off by default (column 2 replays the same saved model answers without it: hands-off 80%, precision 100%, nothing else changed). Column 4 is the check on cases not used for that decision.
- **Remaining escalations are intended.** The cases that still go to the expert are the ten per 50 that the generator marks as needing a person (missing landlord PAN, unexplained property purchase, income above Rs 50 lakh, foreign RSUs, crypto).

## Per-run reports

- [Dev set, reviewer can block](dev_reviewer_gate/results.md)
- [Dev set, reviewer off (replay)](dev_reviewer_off/results.md)
- [Held-out set, reviewer off](heldout/results.md)

## Limits you should read before trusting this

- The documents are synthetic and machine-generated, three layouts with clean text. A model reading them is an easy task; real scans, photos and unusual layouts are untested, so reading accuracy on real documents may be much lower.
- The correct answers come from our own tax engine applied to the true facts, so this measures reading, reconciling and deciding, not tax law. The engine is checked by hand-worked tests, not yet by the official calculator.
- One repeat per run: the free Gemini tier allows only 15 requests a minute and a daily cap, and the 3-repeat plan was cut short. Run-to-run variation is not measured.
- The held-out run covers 29 cases, not 50, so its per-trap counts are small (see its report).
- Changing the reviewer after seeing dev-set results is a design decision informed by that data; the held-out column is there so you can see it holds on other cases.
"""
    (BENCH / "results.md").write_text(text, encoding="utf-8")
    shutil.copyfile(BENCH / "heldout" / "chart.png", BENCH / "chart.png")
    print("wrote", BENCH / "results.md")


if __name__ == "__main__":
    main()
